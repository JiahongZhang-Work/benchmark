def main() -> None:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    total = 0
    with open(OUT, "w", encoding="utf-8") as f:
        for sid, _topic, qas in TOPICS:
            n = len(qas)
            for i, (q, a) in enumerate(qas):
                if i == 0:
                    stage = "start"
                elif i == n - 1:
                    stage = "end"
                else:
                    stage = f"stage-{i}"
                parent = "" if i == 0 else f"{sid}_msg_{i - 1}"
                rec = {
                    "question": q,
                    "answer": a,
                    "agent_hint": {
                        "session_id": sid,
                        "parent_session_id": parent,
                        "cache_control": {},
                        "context_management": {},
                        "stage": stage,
                    },
                }
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                total += 1
    print(f"written {OUT}: {len(TOPICS)} sessions, {total} requests")


if __name__ == "__main__":
    main()
